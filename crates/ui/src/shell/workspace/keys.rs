pub fn bind_keys(cx: &mut App) {
    let normal = Some("Workspace && mode == normal");
    // Only in normal mode: an answer field in the Owner questions tab sits
    // inside the task view, and while it has focus the keys type.
    let detail = Some("(Workspace && mode == normal) > DetailPane");
    cx.bind_keys([
        KeyBinding::new("j", MoveDown, normal),
        KeyBinding::new("down", MoveDown, normal),
        KeyBinding::new("k", MoveUp, normal),
        KeyBinding::new("up", MoveUp, normal),
        KeyBinding::new("ctrl-n", MoveDown, normal),
        KeyBinding::new("ctrl-p", MoveUp, normal),
        KeyBinding::new("g g", GoTop, normal),
        KeyBinding::new("shift-g", GoBottom, normal),
        KeyBinding::new("enter", Open, normal),
        // View history, as nvim's jump list. Claims is a view too, so the
        // keys work over it as well.
        KeyBinding::new("ctrl-o", ViewBack, normal),
        KeyBinding::new("ctrl-i", ViewForward, normal),
        KeyBinding::new("ctrl-o", ViewBack, Some("Workspace && mode == overlay")),
        KeyBinding::new("ctrl-i", ViewForward, Some("Workspace && mode == overlay")),
        KeyBinding::new("/", FocusFilter, normal),
        KeyBinding::new(":", OpenPalette, normal),
        KeyBinding::new("e", EditDescription, normal),
        KeyBinding::new("shift-e", EditExternal, normal),
        // Tabs in the task view, as in vim. They work from the list too, on
        // the task it shows.
        KeyBinding::new("g t", NextTab, normal),
        KeyBinding::new("g shift-t", PrevTab, normal),
        KeyBinding::new("g t", NextTab, detail),
        KeyBinding::new("g shift-t", PrevTab, detail),
        KeyBinding::new("?", ToggleHelp, normal),
        KeyBinding::new("g c", ShowClaims, normal),
        KeyBinding::new("g i", ShowInbox, normal),
        // Groups fold like vim folds.
        KeyBinding::new("z a", ToggleGroup, normal),
        KeyBinding::new("z c", CloseGroup, normal),
        KeyBinding::new("z o", OpenGroup, normal),
        KeyBinding::new("z shift-m", CloseAllGroups, normal),
        KeyBinding::new("z shift-r", OpenAllGroups, normal),
        // Panes: h / l, or the Ctrl-A prefix, as in tmux and herdr.
        KeyBinding::new("h", FocusList, normal),
        KeyBinding::new("l", FocusDetail, normal),
        KeyBinding::new("ctrl-a h", FocusList, normal),
        KeyBinding::new("ctrl-a l", FocusDetail, normal),
        // Up and down match the stacked layout, where the task view is below.
        KeyBinding::new("ctrl-a j", FocusDetail, normal),
        KeyBinding::new("ctrl-a k", FocusList, normal),
        // The task view scrolls with the same keys the list moves with. Its
        // context is deeper, so these win over the list bindings.
        KeyBinding::new("j", ScrollDown, detail),
        KeyBinding::new("down", ScrollDown, detail),
        KeyBinding::new("ctrl-n", ScrollDown, detail),
        KeyBinding::new("k", ScrollUp, detail),
        KeyBinding::new("up", ScrollUp, detail),
        KeyBinding::new("ctrl-p", ScrollUp, detail),
        KeyBinding::new("ctrl-d", HalfPageDown, detail),
        KeyBinding::new("ctrl-u", HalfPageUp, detail),
        KeyBinding::new("g g", ScrollTop, detail),
        KeyBinding::new("shift-g", ScrollBottom, detail),
        // The editor's vim normal mode reaches the palette, help and panes.
        KeyBinding::new(":", OpenPalette, Some(vim_editor::NORMAL)),
        KeyBinding::new("?", ToggleHelp, Some(vim_editor::NORMAL)),
        KeyBinding::new("ctrl-a h", FocusList, Some(vim_editor::NORMAL)),
        KeyBinding::new("ctrl-a l", FocusDetail, Some(vim_editor::NORMAL)),
        KeyBinding::new("ctrl-a j", FocusDetail, Some(vim_editor::NORMAL)),
        KeyBinding::new("ctrl-a k", FocusList, Some(vim_editor::NORMAL)),
        KeyBinding::new("cmd-s", Save, Some(CONTEXT)),
        KeyBinding::new("cmd-b", ToggleSidebar, Some(CONTEXT)),
        KeyBinding::new("c", NewIssue, normal),
        KeyBinding::new("x", ToggleMark, normal),
        KeyBinding::new("ctrl-c", Cancel, Some(create::CONTEXT)),
        // Deeper than the field's own Tab, which would type an indent.
        KeyBinding::new("tab", create::SwitchField, Some("CreateForm > Input")),
        KeyBinding::new("shift-tab", create::SwitchField, Some("CreateForm > Input")),
        // The sidebar moves like the list. Its context is deeper, so these
        // win over the list bindings.
        KeyBinding::new("j", SidebarDown, Some(sidebar::CONTEXT)),
        KeyBinding::new("down", SidebarDown, Some(sidebar::CONTEXT)),
        KeyBinding::new("ctrl-n", SidebarDown, Some(sidebar::CONTEXT)),
        KeyBinding::new("k", SidebarUp, Some(sidebar::CONTEXT)),
        KeyBinding::new("up", SidebarUp, Some(sidebar::CONTEXT)),
        KeyBinding::new("ctrl-p", SidebarUp, Some(sidebar::CONTEXT)),
        KeyBinding::new("g g", SidebarTop, Some(sidebar::CONTEXT)),
        KeyBinding::new("shift-g", SidebarBottom, Some(sidebar::CONTEXT)),
        KeyBinding::new("l", LeaveSidebar, Some(sidebar::CONTEXT)),
        KeyBinding::new("enter", LeaveSidebar, Some(sidebar::CONTEXT)),
        KeyBinding::new("escape", LeaveSidebar, Some(sidebar::CONTEXT)),
        KeyBinding::new("ctrl-a l", LeaveSidebar, Some(sidebar::CONTEXT)),
        // Ctrl-C cancels like Esc while typing and closes the help, as in
        // nvim.
        KeyBinding::new("ctrl-c", Cancel, Some(CONTEXT)),
        // Menus, including the right-click menu and the Labels dropdown.
        KeyBinding::new(
            "ctrl-n",
            gpui_kit::base::actions::SelectDown,
            Some("PopupMenu"),
        ),
        KeyBinding::new(
            "ctrl-p",
            gpui_kit::base::actions::SelectUp,
            Some("PopupMenu"),
        ),
        KeyBinding::new("j", gpui_kit::base::actions::SelectDown, Some("PopupMenu")),
        KeyBinding::new("k", gpui_kit::base::actions::SelectUp, Some("PopupMenu")),
        KeyBinding::new("ctrl-c", gpui_kit::base::actions::Cancel, Some("PopupMenu")),
        KeyBinding::new("ctrl-n", SelectNext, Some("Palette")),
        KeyBinding::new("ctrl-p", SelectPrev, Some("Palette")),
        KeyBinding::new("ctrl-n", SelectNext, Some("Filter")),
        KeyBinding::new("ctrl-p", SelectPrev, Some("Filter")),
        // Escape works in both modes. Inputs and the editor handle Escape
        // first and pass it on when they have nothing to dismiss.
        KeyBinding::new("escape", Back, Some(CONTEXT)),
    ]);
    vim_editor::bind_keys(cx);
    crate::docs::bind_keys(cx);
    crate::inbox::bind_keys(cx);
    crate::settings::view::bind_keys(cx);
    crate::issues::claims::bind_keys(cx);
}

